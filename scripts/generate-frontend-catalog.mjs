import ts from "typescript";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const readers = [], actions = [];
for (const directory of ["lib/views", "app/actions"]) {
  for (const name of readdirSync(path.join(root, directory)).filter((item) => item.endsWith(".ts")).sort()) {
    const file = `${directory}/${name}`;
    const source = ts.createSourceFile(file, readFileSync(path.join(root, file), "utf8"), ts.ScriptTarget.Latest, true);
    for (const node of source.statements) {
      if (!ts.isFunctionDeclaration(node) || !node.name || !node.modifiers?.some((item) => item.kind === ts.SyntaxKind.ExportKeyword) || !node.modifiers.some((item) => item.kind === ts.SyntaxKind.AsyncKeyword)) continue;
      const entry = { module: file.replace(/\.ts$/, ""), name: node.name.text, id: `${name.replace(/\.ts$/, "")}:${node.name.text}` };
      (directory === "lib/views" ? readers : actions).push(entry);
    }
  }
}
const all = [...readers, ...actions];
const imports = all.map((item, index) => `import { ${item.name} as endpoint${index} } from "@/${item.module}";`).join("\n");
const registry = (items) => items.map((item) => `  ${JSON.stringify(item.id)}: endpoint${all.indexOf(item)},`).join("\n");
const outputs = {
  "lib/frontend/registry.ts": `// Generated by scripts/generate-frontend-catalog.mjs. Fixed endpoint allowlist.\nimport "server-only";\n${imports}\n\nexport const viewReaders = Object.freeze({\n${registry(readers)}\n});\nexport const backendActions = Object.freeze({\n${registry(actions)}\n});\n`,
  "frontend/catalog.json": JSON.stringify({ readers, actions }, null, 2) + "\n",
};
for (const [file, source] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path.join(root, file), "utf8") !== source) throw new Error("Frontend endpoint catalog is stale. Run npm run frontend:catalog.");
  } else writeFileSync(path.join(root, file), source);
}
console.log(`Frontend catalog verified: ${readers.length} views, ${actions.length} actions.`);
